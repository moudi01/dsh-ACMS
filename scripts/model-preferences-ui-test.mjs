import { chromium, expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { startPreview } from "./preview-server.mjs";
const server = await startPreview();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
const errors = []; const diagnostics = [];
page.on("pageerror", error => errors.push(error.message));
page.on("request", request => { if (/model-(check|details)/.test(request.url())) diagnostics.push(request.url()); });
await mkdir("test-results/ui", { recursive: true });
try {
  await page.goto(server.url);
  await page.getByRole("button", { name: "模型列表", exact: true }).click();
  await expect(page.getByRole("heading", { name: "模型偏好", exact: true })).toBeVisible();
  await expect(page.getByText("没有偏好时使用 DSH 默认与固定入口顺序", { exact: false })).toBeVisible();
  expect(diagnostics.length).toBe(0);
  await page.getByLabel("添加模型到偏好").selectOption("deepseek-reasoner|simulation|preview");
  await page.getByRole("button", { name: "添加", exact: true }).click();
  await page.getByLabel("添加模型到偏好").selectOption("deepseek-flash|simulation|preview");
  await page.getByRole("button", { name: "添加", exact: true }).click();
  await expect(page.locator(".acms-preference-list > li")).toHaveCount(2);
  await page.getByRole("button", { name: "上移 2", exact: true }).click();
  await page.getByLabel("偏好标签 1").fill("首选模型");
  expect(diagnostics.length).toBe(0);
  await page.getByRole("button", { name: "保存偏好", exact: true }).click();
  await expect(page.getByText("模型偏好已保存", { exact: true })).toBeVisible();
  let saved = server.company.store.get("modelPreferences", "model");
  expect(saved.order.length).toBe(2);
  expect(saved.order[0].model).toBe("deepseek-flash");
  expect(saved.order[0].label).toBe("首选模型");
  expect(saved.revision).toBe(1);
  expect(diagnostics.length).toBe(0);
  await page.screenshot({ path: "test-results/ui/model-preferences.png", fullPage: true });
  await page.getByRole("button", { name: "清除偏好", exact: true }).click();
  await expect(page.getByText("模型偏好已清除；自动选择回到 DSH 默认与稳定入口顺序", { exact: true })).toBeVisible();
  saved = server.company.store.get("modelPreferences", "model");
  expect(saved.order.length).toBe(0);
  expect(saved.revision).toBe(2);
  expect(diagnostics.length).toBe(0);
  const snapshot = server.company.snapshot();
  const task = snapshot.tasks.find(item => item.title === "确认品牌素材") ?? snapshot.tasks[0];
  server.company.store.transaction(() => { server.company.store.put("attempts", { id: "attempt_ui_selection", taskId: task.id, goalId: task.goalId, agentId: task.agentId, kind: task.kind, provider: "simulation", model: "deepseek-reasoner", llmProvider: "preview", status: "completed", contextKey: "acms:ui:selection", startedAt: new Date().toISOString(), taskGeneration: task.generation, selection: { selectorVersion: "1", status: "selected", binding: { mode: "preference", source: "user-preference", preferenceId: "pref_ui" }, chosen: { candidateId: "cand_ui", model: "deepseek-reasoner", provider: "simulation", llmProvider: "preview", reasoningEffort: null, origin: "internal", persistent: false }, preferenceIndex: 0, considered: [], fallbacks: [{ candidateId: "cand_other", model: "offline-test-model", provider: "simulation", reason: "health_unavailable" }], truncated: { considered: false, fallbacks: false }, blocked: null } }); server.company.store.event("task.changed", task.id, { fields: ["attempt"] }, { kind: "owner", id: "owner" }); });
  await page.waitForTimeout(500);
  await page.getByRole("button", { name: "任务工作台", exact: true }).click();
  await page.getByRole("button", { name: "看板", exact: true }).click();
  await page.getByRole("heading", { name: task.title, exact: true }).click();
  await page.locator("details.acms-run").first().locator("summary").click();
  await expect(page.getByText("用户偏好第 1 项", { exact: true })).toBeVisible();
  await expect(page.getByText(/offline-test-model：health_unavailable/)).toBeVisible();
  await expect(page.getByText("模型通道", { exact: true }).first()).toBeVisible();
  await page.screenshot({ path: "test-results/ui/model-selection-evidence.png", fullPage: true });
  await page.getByRole("button", { name: "关闭任务详情" }).click();
  if (errors.length) throw new Error(errors.join("\\n"));
  const report = { passed: true, mode: "isolated preview harness with simulation provider", checked: ["ordered preference add, move, label, save, clear", "preferences persisted through command/domain with revision", "viewing and saving preferences never requested model-check or model-details", "attempt selection basis and fallback reasons rendered in task detail"], screenshots: ["test-results/ui/model-preferences.png", "test-results/ui/model-selection-evidence.png"], diagnostics };
  await writeFile("test-results/ui/model-preferences-report.json", JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) { console.error("Browser errors:", errors); await page.screenshot({ path: "test-results/ui/model-preferences-failure.png", fullPage: true }); throw error; } finally { await browser.close(); await server.close(); }
